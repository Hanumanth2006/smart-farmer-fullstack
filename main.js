// ======================================================
// 3. CROP SEARCH + CATEGORY FILTER
// ======================================================

const cropSearch = document.getElementById("cropSearch");
const cropCategory = document.getElementById("cropCategory");


function filterCrops() {

    if (!cropSearch || !cropCategory) {
        return;
    }


    const searchText =
        cropSearch.value.toLowerCase().trim();

    const selectedCategory =
        cropCategory.value;


    const filteredCrops =
        cropDatabase.filter(function(crop) {

            const matchesSearch =
                crop.name
                    .toLowerCase()
                    .includes(searchText);


            const matchesCategory =
                selectedCategory === "all" ||
                crop.category === selectedCategory;


            return matchesSearch &&
                   matchesCategory;

        });


    displayCrops(filteredCrops);

}


if (cropSearch) {
    cropSearch.addEventListener(
        "input",
        filterCrops
    );
}


if (cropCategory) {
    cropCategory.addEventListener(
        "change",
        filterCrops
    );
}


// ======================================================
// 4. PRODUCT DETAILS
// ======================================================

function openProductDetails(cropName) {

    const crop =
        cropDatabase.find(function(item) {
            return item.name === cropName;
        });


    if (!crop) {
        return;
    }


    localStorage.setItem(
        "selectedCrop",
        JSON.stringify(crop)
    );


    window.location.href =
        "product-details.html";

}


