// 2. DISPLAY CROPS
// ======================================================

const cropContainer = document.getElementById("cropContainer");

function displayCrops(crops) {

    if (!cropContainer) {
        return;
    }

    cropContainer.innerHTML = "";

    if (crops.length === 0) {

        cropContainer.innerHTML = `
            <div class="no-crops">
                <h2>😔 No crops found</h2>
                <p>Try another crop name or category.</p>
            </div>
        `;

        return;
    }


    crops.forEach(function(crop) {

        const card = document.createElement("div");

        card.className = "market-card";

        card.dataset.category = crop.category;


        card.innerHTML = `

            <div class="market-image">
                ${crop.icon}
            </div>

            <div class="market-info">

                <span class="category">
                    ${crop.category}
                </span>

                <h2>${crop.name}</h2>

                <p>
                    Fresh quality ${crop.name}
                    directly from farmers.
                </p>

                <p class="farmer">
                    👨‍🌾 Farmer: ${crop.farmer}
                </p>

                <p class="location">
                    📍 ${crop.location}
                </p>

                <h3>
                    ₹${crop.price.toLocaleString("en-IN")}
                    / Quintal
                </h3>

                <button
                    class="view-btn"
                    onclick="openProductDetails('${crop.name}')"
                >
                    View Details
                </button>

            </div>
        `;


        cropContainer.appendChild(card);

    });

}


